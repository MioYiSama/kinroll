/** Manual equivalent of CLIP's Unicode token regex.
 * Kotlin/Native's negated class combining \s and \p categories incorrectly matches spaces.
 * BMP categories use the common stdlib; supplementary categories use Unicode 17.0.0 ranges.
 */
internal object ClipTextPieces {
    private val contractions = arrayOf("'s", "'t", "'re", "'ve", "'m", "'ll", "'d")

    fun normalize(text: String): String = buildString {
        var pendingSpace = false
        for (char in text.lowercase()) {
            if (char.isWhitespace() || char == '\u0085') pendingSpace = isNotEmpty()
            else {
                if (pendingSpace) append(' ')
                append(char)
                pendingSpace = false
            }
        }
    }

    fun split(text: String): Sequence<String> = sequence {
        var cursor = 0
        while (cursor < text.length) {
            if (text[cursor].isWhitespace() || text[cursor] == '\u0085') { cursor++; continue }
            val start = cursor
            val contraction = if (text[cursor] == '\'') contractions.firstOrNull { text.startsWith(it, cursor) } else null
            if (contraction != null) {
                cursor += contraction.length
            } else {
                val first = codePoint(text, cursor)
                val kind = category(first)
                cursor += if (first > 0xFFFF) 2 else 1
                // Numeric tokens contain one Unicode scalar, unlike letter and punctuation runs.
                if (kind != 2) while (cursor < text.length) {
                    if (text[cursor].isWhitespace() || text[cursor] == '\u0085') break
                    val next = codePoint(text, cursor)
                    if (category(next) != kind) break
                    cursor += if (next > 0xFFFF) 2 else 1
                }
            }
            yield(text.substring(start, cursor))
        }
    }

    private fun codePoint(text: String, offset: Int): Int {
        val high = text[offset]
        if (high.isHighSurrogate() && offset + 1 < text.length && text[offset + 1].isLowSurrogate()) {
            return 0x10000 + ((high.code - 0xD800) shl 10) + text[offset + 1].code - 0xDC00
        }
        return high.code
    }

    private fun category(codePoint: Int): Int {
        if (codePoint <= 0xFFFF) return when (codePoint.toChar().category) {
            CharCategory.UPPERCASE_LETTER, CharCategory.LOWERCASE_LETTER, CharCategory.TITLECASE_LETTER,
            CharCategory.MODIFIER_LETTER, CharCategory.OTHER_LETTER -> 1
            CharCategory.DECIMAL_DIGIT_NUMBER, CharCategory.LETTER_NUMBER, CharCategory.OTHER_NUMBER -> 2
            else -> 0
        }
        var low = 0
        var high = supplementary.size / 3 - 1
        while (low <= high) {
            val middle = (low + high) ushr 1
            val index = middle * 3
            when {
                codePoint < supplementary[index] -> high = middle - 1
                codePoint > supplementary[index + 1] -> low = middle + 1
                else -> return supplementary[index + 2]
            }
        }
        return 0
    }

